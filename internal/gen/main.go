package main

import (
	"fmt"
	"log"
	"os"
	"strings"
	"text/template"
)

type Field struct {
	GoName string
	JSON   string
	GoType string
}

const fileTmpl = `// Code generated by internal/gen. DO NOT EDIT.
package models

type {{.UnitsName}} struct {
{{- range .Fields}}
	{{.GoName}} *string ` + "`" + `json:"{{.JSON}},omitempty"` + "`" + `
{{- end}}
}

type {{.WeatherName}} struct {
{{- range .Fields}}
	{{.GoName}} {{.SliceType}} ` + "`" + `json:"{{.JSON}},omitempty"` + "`" + `
{{- end}}
}
`

type fileData struct {
	UnitsName   string
	WeatherName string
	Fields      []fieldWithSlice
}

type fieldWithSlice struct {
	Field
	SliceType string
}

func writeGroup(path, unitsName, weatherName string, fields []Field) error {
	const operation = "wx-api.internal.gen.main.writeGroup"

	data := fileData{UnitsName: unitsName, WeatherName: weatherName}
	for _, field := range fields {
		data.Fields = append(data.Fields, fieldWithSlice{
			Field:     field,
			SliceType: "[]" + field.GoType,
		})
	}

	tmpl := template.Must(template.New("file").Parse(fileTmpl))

	var sb strings.Builder
	if err := tmpl.Execute(&sb, data); err != nil {
		return fmt.Errorf("%s: error executing template for %s: %w", operation, path, err)
	}

	return os.WriteFile(path, []byte(sb.String()), 0644)
}

